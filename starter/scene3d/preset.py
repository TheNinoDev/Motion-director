#!/usr/bin/env python3
"""Create a valid standalone scene plan from a proven preset, no GUI."""
import argparse, copy, json, sys
from pathlib import Path
HERE=Path(__file__).resolve().parent
NAMES=('hero','grid-helix','ring','tunnel','sphere','wordmark')
def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('preset',choices=NAMES);p.add_argument('output',type=Path)
    p.add_argument('--glyphs',default='AXO');p.add_argument('--seconds',type=float,default=2)
    p.add_argument('--width',type=int,default=360);p.add_argument('--height',type=int,default=640);p.add_argument('--fps',type=int,default=30)
    p.add_argument('--points',type=Path,help='Required for wordmark: custom XYZ point array, generated by silhouette.py')
    a=p.parse_args()
    if not (0.1<=a.seconds<=30 and 1<=a.fps<=120 and 2<=a.width<=4096 and 2<=a.height<=4096 and a.width%2==0 and a.height%2==0):p.error('Use positive even canvas dimensions, 1–120 fps, 0.1–30 seconds.')
    if not a.glyphs or any(not (33<=ord(c)<=126) for c in a.glyphs):p.error('Use printable ASCII glyphs without spaces.')
    d=json.loads((HERE/'demo.json').read_text());s=copy.deepcopy(d['scenes'][NAMES.index(a.preset)])
    if a.preset=='wordmark':
        if not a.points:p.error('Supply --points for the actual product wordmark; demo text is not a production asset.')
        pts=json.loads(a.points.read_text());
        if not isinstance(pts,list) or not 1<=len(pts)<=10000 or any(not isinstance(q,list) or len(q)!=3 or any(type(v) not in (float,int) or not __import__('math').isfinite(v) for v in q) for q in pts):p.error('Expected array of finite XYZ triples.')
        s['points']=pts;s['count']=len(pts)
    elif a.points:p.error('--points is only for wordmark.')
    s.update(start=0,end=max(1,round(a.seconds*a.fps)),glyphs=a.glyphs[:1] if a.preset=='hero' else a.glyphs)
    d.update(width=a.width,height=a.height,fps=a.fps,scenes=[s]);a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text(json.dumps(d,indent=2)+'\n');print(a.output)
if __name__=='__main__':main()
